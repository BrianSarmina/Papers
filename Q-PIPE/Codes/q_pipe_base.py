def iqft(wires):
    """
    Inverse Quantum Fourier Transform (iQFT) from scratch.

    Args:
        wires (Sequence[int] or Sequence[str]): wires in the register order.
    """

    n = len(wires)

    # ------------------------------------------------------------
    # Step 1) Bit-reversal via SWAPs (reverse wire order)
    # ------------------------------------------------------------
    for i in range(n // 2):
        qml.SWAP(wires=[wires[i], wires[n - 1 - i]])

    # ------------------------------------------------------------
    # Step 2) Core iQFT layers
    #   For each target wire j (from 0 to n-1):
    #     - apply controlled phases from higher-index wires k>j
    #     - then apply Hadamard on wire j
    # ------------------------------------------------------------
    for j in range(n):
        # Controlled phase rotations with negative angles
        # control: wires[k], target: wires[j]
        for k in range(j + 1, n):
            angle = -np.pi / (2 ** (k - j))
            qml.ControlledPhaseShift(angle, wires=[wires[k], wires[j]])

        # Hadamard at the end of this stage
        qml.Hadamard(wires=wires[j])

