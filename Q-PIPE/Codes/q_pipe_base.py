def phase_encoding_circuit(image_matrix):
    est_wires = list(range(n_estimation_wires))
    tgt_wires = list(range(n_estimation_wires, n_estimation_wires + n_image_wires))

    # PASO A: Superposición
    # Ponemos los qubits de estimación en |+> para interferometría
    for w in est_wires:
        qml.Hadamard(wires=w)

    # Ponemos los qubits de imagen (target) en superposición para procesar todos los píxeles
    for w in tgt_wires:
        qml.Hadamard(wires=w)

    # PASO B: Aplicación de Unitarios Controlados (Phase Kickback)
    # Iteramos sobre los cables de estimación desde el LSB (menos significativo) hacia arriba.
    # En QPE estándar, el wire j controla U^(2^j).
    # PennyLane ordena los wires de estimación tal que wires[n-1] es el bit de menor peso para la fase.

    for i, est_wire in enumerate(reversed(est_wires)):
        # i será 0, 1, 2... correspondiente a la potencia 2^0, 2^1...
        power = 2**i

        # Aplicamos C-U^(power)
        # Esto inyecta la fase relativa en el qubit 'est_wire'
        apply_controlled_image_unitary(image_matrix, tgt_wires, est_wire, power)
        qml.Barrier()

    # PASO C: Transformada Cuántica de Fourier Inversa (QFT_dagger)
    # Convierte la información codificada en fase a la base computacional (bits)
    qml.adjoint(qml.QFT)(wires=est_wires)

    return qml.probs(wires=est_wires + tgt_wires)

