@qml.qnode(dev)
def dual_phase_encoding_circuit(image_matrix_1, image_matrix_2):
    est_wires = list(range(n_estimation_wires))
    tgt_wires = list(range(n_estimation_wires, n_estimation_wires + n_image_wires))

    # PASO A: Superposición Total
    for w in est_wires:
        qml.Hadamard(wires=w)
    for w in tgt_wires:
        qml.Hadamard(wires=w)

    # PASO B: Acumulación de Fases (Imagen 1 + Imagen 2)
    # Iteramos sobre los cables de estimación
    for i, est_wire in enumerate(reversed(est_wires)):
        power = 2**i

        # 1. Inyectar Fase de la Imagen 1
        apply_controlled_image_unitary(image_matrix_1, tgt_wires, est_wire, power)

        # 2. Inyectar Fase de la Imagen 2 (ACUMULACIÓN)
        # Al aplicar esto secuencialmente antes de la QFT inversa,
        # las fases se suman matemáticamente: e^(i*phi1) * e^(i*phi2) = e^(i*(phi1+phi2))
        apply_controlled_image_unitary(image_matrix_2, tgt_wires, est_wire, power)

        qml.Barrier() # Para visualizar separación de pasos de potencia

    # PASO C: Recuperación (QFT Inversa)
    # Se realiza UNA sola vez al final para decodificar la fase total acumulada
    qml.adjoint(qml.QFT)(wires=est_wires)

    return qml.probs(wires=est_wires + tgt_wires)

