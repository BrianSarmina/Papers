def extract_gradient_magnitude(probs, shape, threshold=0.001):
    weighted_mag_sum = np.zeros(shape, dtype=float)
    prob_sum = np.zeros(shape, dtype=float)

    for k, p in enumerate(probs):
        if p > threshold:
            bin_k = format(k, f'0{total_wires}b')
            est_int = int(bin_k[:n_estimation_wires], 2)
