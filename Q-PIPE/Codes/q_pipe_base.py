# --- 1. Definición del Oráculo (Misma lógica, reutilizable) ---
def controlled_phase_for_state_power(phi, wires_list, control_values, power):
    """ Aplica la fase (phi * power) al estado especificado. """
    w0, w1 = wires_list[0], wires_list[1]

    # 1. Inversión de bits para seleccionar estado
    for i in range(len(control_values)):
        if control_values[i] == 0:
            qml.PauliX(wires=wires_list[i])

    # 2. Fase Controlada Potenciada
    current_phi = phi * power
    qml.ControlledPhaseShift(current_phi, wires=[w0, w1])

    # 3. Reversión (Uncompute)
    for i in range(len(control_values)):
        if control_values[i] == 0:
            qml.PauliX(wires=wires_list[i])

def apply_controlled_image_unitary(image_matrix, target_wires, control_wire, power):
    """ Aplica U^power de una matriz de imagen dada. """
    def unitary_logic():
        controlled_phase_for_state_power(image_matrix[0][0], target_wires, [0, 0], power)
        controlled_phase_for_state_power(image_matrix[0][1], target_wires, [0, 1], power)
        controlled_phase_for_state_power(image_matrix[1][0], target_wires, [1, 0], power)
        controlled_phase_for_state_power(image_matrix[1][1], target_wires, [1, 1], power)

    qml.ctrl(unitary_logic, control=control_wire)()


