def controlled_phase_for_state_power(phi, wires_list, control_values, power):
    #- Aplica la fase (phi * power) al estado especificado dinámicamente.
    # 1. Inversión de bits para seleccionar estado
    for i, bit in enumerate(control_values):
        if bit == 0:
            qml.PauliX(wires=wires_list[i])

    # 2. Fase Controlada Potenciada (Generalizada para n qubits objetivo)
    current_phi = phi * power
    if len(wires_list) == 1:
        qml.PhaseShift(current_phi, wires=wires_list[0])
    else:
        # Controlamos con todos los qubits excepto el último
        controls = wires_list[:-1]
        target = wires_list[-1]
        qml.ctrl(qml.PhaseShift, control=controls)(current_phi, wires=target)

    # 3. Reversión (Uncompute)
    for i, bit in enumerate(control_values):
        if bit == 0:
            qml.PauliX(wires=wires_list[i])

def apply_controlled_image_unitary(image_matrix, target_wires, control_wire, power):
    #- Aplica U^power iterando sobre todos los píxeles de una matriz N x M.
    flat_image = image_matrix.flatten()
    n_qubits = len(target_wires)

    # Genera todas las combinaciones binarias posibles para los qubits objetivo
    binary_states = list(itertools.product([0, 1], repeat=n_qubits))

    def unitary_logic():
        for i, pixel_phase in enumerate(flat_image):
            if pixel_phase > 0: # Optimización: Omitir rotaciones de fase 0
                control_values = binary_states[i]
                controlled_phase_for_state_power(pixel_phase, target_wires, control_values, power)

    # Controlamos toda la operación desde el qubit de estimación
    qml.ctrl(unitary_logic, control=control_wire)()


