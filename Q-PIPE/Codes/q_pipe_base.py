### (2) Oráculo optimizado (Código Gray)
def apply_phases_with_gray_code(flat_phases, img_wires, est_wire, power):
    """
    Aplica las fases de toda la imagen utilizando una trayectoria de Código Gray.
    Elimina la necesidad de hacer uncompute/compute completo por cada píxel.
    """
    n = len(img_wires)
    total_states = 2**n

    # Generación de la secuencia Gray: g_i = i XOR (i >> 1)
    gray_seq = [i ^ (i >> 1) for i in range(total_states)]

    # 1. Mapeo Inicial: Convertir el estado inicial |00...0> al target |11...1>
    # Empezamos en gray_seq[0] = 0. Invertimos todos los cables.
    for w in img_wires:
        qml.PauliX(wires=w)

    target_wire = img_wires[-1]
    control_wires = [est_wire] + list(img_wires[:-1])

    # 2. Recorrido de la secuencia
    for step in range(total_states):
        curr_gray = gray_seq[step]
        pixel_idx = curr_gray

        # Inyectar la fase si el píxel existe y no es cero (ahorra compuertas de fase)
        # Nota: NO saltamos el paso en el ciclo, ya que la secuencia Gray de compuertas X debe mantenerse.
        if pixel_idx < len(flat_phases):
            phi = flat_phases[pixel_idx]
            if abs(phi) > 1e-5:
                current_phi = phi * power
                qml.ctrl(qml.PhaseShift, control=control_wires)(current_phi, wires=target_wire)

        # 3. Transición al siguiente estado Gray usando una sola compuerta X
        if step < total_states - 1:
            next_gray = gray_seq[step + 1]
            diff = curr_gray ^ next_gray

            # Identificar la posición del bit que cambió (0-indexado desde LSB)
            bit_changed_from_right = int(np.log2(diff))
            # Mapear a los cables de imagen (MSB a LSB)
            wire_to_flip = img_wires[n - 1 - bit_changed_from_right]

            qml.PauliX(wires=wire_to_flip)

    # 4. Uncompute Final
    # Revertir los cables a su estado base original para no corromper la QFT posterior.
    # Los cables que terminaron invertidos son aquellos correspondientes a los ceros en el último estado Gray.
    last_gray_bin = format(gray_seq[-1], f'0{n}b')
    for i, bit in enumerate(last_gray_bin):
        if bit == '0':
            qml.PauliX(wires=img_wires[i])

