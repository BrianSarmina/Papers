def encode_phase_on_target(phi, wires, state):
    """ Aplica la fase phi a un estado base específico de los cables dados. """
    # X gates para seleccionar el estado
    for i, s in enumerate(state):
        if s == 0:
            qml.PauliX(wires=wires[i])
    qml.Barrier()
    # Al aplicar PhaseShift a uno de los cables cuando está en |1>,
    # la fase se añade a todo el estado (rama de la superposición).
    qml.PhaseShift(phi, wires=wires[0])
    qml.Barrier()
    # Reversión
    for i, s in enumerate(state):
        if s == 0:
            qml.PauliX(wires=wires[i])
